"""Database compatibility layer for FINZ: PostgreSQL on hosted deployments.
Set DATABASE_URL to a PostgreSQL connection URL for persistent storage.
Legacy SQLite is retained by main.py for local development.
"""
import re
import psycopg
from psycopg.rows import dict_row

class HybridRow(dict):
    """Provide sqlite3.Row-style access by both column name and integer index."""
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)

def hybrid_row_factory(cursor):
    fields = [c.name for c in cursor.description] if cursor.description else []
    def make(values):
        return HybridRow(zip(fields, values))
    return make

class PostgresConnection:
    def __init__(self, url):
        self.conn = psycopg.connect(url, row_factory=hybrid_row_factory, connect_timeout=15)

    def execute(self, statement, parameters=()):
        statement = statement.strip()
        if statement.upper().startswith("PRAGMA "):
            return self.conn.execute("SELECT 1 WHERE 1=0")
        if "last_insert_rowid()" in statement.lower():
            statement = re.sub(r"last_insert_rowid\(\)", "LASTVAL()", statement, flags=re.I)
        statement = statement.replace("?", "%s")
        return self.conn.execute(statement, parameters)

    def executemany(self, statement, parameters):
        with self.conn.cursor() as cur:
            cur.executemany(statement.replace("?", "%s"), parameters)

    def executescript(self, script):
        for stmt in script.split(";"):
            stmt = stmt.strip()
            if not stmt:
                continue
            stmt = re.sub(r"INTEGER PRIMARY KEY", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", stmt, flags=re.I)
            self.execute(stmt)

    def commit(self):
        self.conn.commit()

    def close(self):
        self.conn.close()
